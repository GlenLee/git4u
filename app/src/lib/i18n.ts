const messages: Record<UiLanguage, Messages> = { zh, en };

export const language = ref<UiLanguage>("zh");

export function setLanguage(next: UiLanguage): void {
  language.value = next;
  if (typeof document !== "undefined") {
    document.documentElement.lang = next === "en" ? "en" : "zh-CN";
  }
}

export function localeTag(): string {
  return language.value === "en" ? "en-US" : "zh-CN";
}

const MID_STATES: Record<string, MessageKey> = {
  "合并中": "midState.merge",
  "rebase 中": "midState.rebase",
  "cherry-pick 中": "midState.cherryPick",
  "revert 中": "midState.revert",
  "bisect 中": "midState.bisect",
};

export function midStateLabel(state: string): string {
  const key = MID_STATES[state];
  return key ? t(key) : state;
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const message = messages[language.value][key];
  let text =
    typeof message === "string"
      ? message
      : Number(params?.n) === 1
        ? message.one
        : message.other;
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match,
    );
  }
  return text;
}

export function messageKeys(): MessageKey[] {
  return Object.keys(zh) as MessageKey[];
}

export function missingKeys(lang: UiLanguage): string[] {
  const dictionary = messages[lang] as Record<string, unknown>;
  return messageKeys().filter((key) => !(key in dictionary));
}
